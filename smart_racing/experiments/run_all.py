"""Run the five experiments of Project.md section 7 and write every CSV, chart,
`environment.json` and `SUMMARY.md` into `experiments/results/`.

    .venv/bin/python -m smart_racing.experiments.run_all            full run
    .venv/bin/python -m smart_racing.experiments.run_all --quick    smoke run -> results/quick/
    options: --runs N (timed runs, default 5), --warmup N, --seed N, --out DIR
"""
from __future__ import annotations

import time

from smart_racing.experiments import common as X
from smart_racing.experiments import (exp1_bfs_dfs, exp2_shortest_path, exp3_knapsack,
                                      exp4_event_queue, exp5_sorting_topk)

EXPERIMENTS = (exp1_bfs_dfs, exp2_shortest_path, exp3_knapsack, exp4_event_queue, exp5_sorting_topk)


def run_all(cfg: X.Config) -> str:
    env = X.write_environment(cfg)
    sections, walls = [], []
    for module in EXPERIMENTS:
        start = time.perf_counter()
        sections.append(module.run(cfg))
        walls.append(f"{module.__name__.rsplit('.', 1)[1]} {time.perf_counter() - start:.0f} s")
        print(f"done: {walls[-1]}", flush=True)
    header = f"""# Experimental studies: measured results

Generated by `.venv/bin/python -m smart_racing.experiments.run_all{' --quick' if cfg.quick else ''}` on {env['recorded_at']}.
Every number below is computed from the CSV files in this directory by the experiment scripts;
rerunning regenerates this file, the CSVs and the charts. {"**Quick smoke configuration: sizes are too small to discuss growth.**" if cfg.quick else ""}

Common method (Project.md section 7, fair timing):

- The experiments call the gameplay implementations in `smart_racing/algorithms/` and
  `smart_racing/engine/events.py` and read their built-in counters. There is no second copy.
- Inputs are generated from seeded `random.Random` instances (base seed {cfg.seed}); competing
  algorithms receive the same input instance.
- Each configuration: {cfg.warmup} untimed warm-up call, then {cfg.runs} timed calls with `time.perf_counter`,
  all in one process on one machine. The garbage collector is run once before each
  configuration and disabled during each timed call. Observers are off. No rendering, file output or artificial delay is
  inside a timed call; input construction and correctness checks are outside.
- Whether data-structure initialization is included is stated in each Procedure paragraph. In
  short: the structures an algorithm creates for itself (queue, heap, visited and parent
  dictionaries, DP table, output list) are included; building the input (graph, item list,
  entry list, a pre-filled event queue) is excluded.
- `*_raw.csv` holds every timed run; `*_summary.csv` holds runs, mean, median and sample
  standard deviation per configuration. Tables below show medians unless a column says otherwise.
- Counters are deterministic and identical across runs. Timings are wall-clock measurements on
  one machine and vary between runs; no complexity class is inferred from a single timing.
  Statements about growth compare several sizes and are stated as consistent with a bound, not
  as proof of it.

Wall time of this run: {", ".join(walls)}.
"""
    text = header + "\n" + "\n".join(sections)
    (cfg.out / "SUMMARY.md").write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    config = X.parse_args(__doc__)
    began = time.perf_counter()
    run_all(config)
    print(f"all experiments finished in {time.perf_counter() - began:.0f} s; outputs in {config.out}")
